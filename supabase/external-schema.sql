create table public.produtividade (
  id bigint generated by default as identity primary key,
  data date not null,
  pelotao text not null,
  efetivo text not null,
  tipo_oc text not null,
  qtde integer not null check (qtde > 0),
  pontos numeric(12,2) not null check (pontos >= 0),
  created_at timestamp with time zone not null default now(),
  localidade text
);

grant select on public.produtividade to anon, authenticated;
grant insert, update, delete on public.produtividade to authenticated;
grant all on public.produtividade to service_role;
grant usage, select on sequence public.produtividade_id_seq to authenticated;
grant all on sequence public.produtividade_id_seq to service_role;

alter table public.produtividade enable row level security;

create policy "Leitura pública"
on public.produtividade
for select
to anon, authenticated
using (true);

create table public.tipos_ocorrencia (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  pontos numeric(12,2) not null check (pontos >= 0),
  ativo boolean not null default true,
  created_at timestamp with time zone not null default now()
);

grant select on public.tipos_ocorrencia to authenticated;
grant all on public.tipos_ocorrencia to service_role;
grant usage, select on sequence public.tipos_ocorrencia_id_seq to authenticated;
grant all on sequence public.tipos_ocorrencia_id_seq to service_role;

alter table public.tipos_ocorrencia enable row level security;

